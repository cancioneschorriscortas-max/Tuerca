/* (v0.44) Normalización galega: as etiquetas de lugar levan artigo (a Ponte, o Radar)
   e ao caer tras "en"/"de" deben contraer (na Ponte, do Radar). Só actúa en gl;
   as secuencias "en a"/"de o" soltas nunca son galego correcto, así que é segura. */
function glNorm(s){
  if(I18N.lang !== 'gl' || typeof s !== 'string') return s;
  return s
    .replace(/\ben a(s?) /g, 'na$1 ').replace(/\ben o(s?) /g, 'no$1 ')
    .replace(/\bEn a(s?) /g, 'Na$1 ').replace(/\bEn o(s?) /g, 'No$1 ')
    .replace(/\bde a(s?) /g, 'da$1 ').replace(/\bde o(s?) /g, 'do$1 ')
    .replace(/\bDe a(s?) /g, 'Da$1 ').replace(/\bDe o(s?) /g, 'Do$1 ');
}
function TXT(clave, params){
  let txt = (LANGS[I18N.lang] && LANGS[I18N.lang][clave])
    || (LANGS.es && LANGS.es[clave])
    || (LANGS.gl && LANGS.gl[clave])
    || clave;
  if(params) for(const k of Object.keys(params)) txt = txt.split('{' + k + '}').join(params[k]);
  return glNorm(txt);
}
