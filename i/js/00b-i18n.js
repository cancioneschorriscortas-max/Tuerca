function TXT(clave, params){
  let txt = (LANGS[I18N.lang] && LANGS[I18N.lang][clave])
    || (LANGS.es && LANGS.es[clave])
    || (LANGS.gl && LANGS.gl[clave])
    || clave;
  if(params) for(const k of Object.keys(params)) txt = txt.split('{' + k + '}').join(params[k]);
  return txt;
}
/* CHROME: ids estáticos → claves (label e tooltip) */
const I18N_CHROME = {
  btnStart: ['btn.start'], btnOnline: ['btn.online', 'tip.online'],
  btnCrisol: ['btn.crisol', 'tip.crisol'], btnMemorial: ['btn.memorial'],
  btnDespiece: ['btn.despiece'], btnCantina: ['btn.cantina', 'tip.cantina'],
  btnCronica: ['btn.cronica', 'tip.cronica'], btnExport: ['btn.export', 'tip.export'],
  btnImport: ['btn.import', 'tip.import'], btnWipe: ['btn.wipe'],
  btnAbort: ['btn.abort'], btnBack: ['btn.back'], btnBioClose: ['btn.close'],
  subTitle: ['sub.titulo'], brHint: ['br.hint'],
};
function aplicarIdioma(){
  for(const id of Object.keys(I18N_CHROME)){
    const el = document.getElementById(id);
    if(!el) continue;
    const [lab, tip] = I18N_CHROME[id];
    el.textContent = TXT(lab);
    if(tip) el.title = TXT(tip);
  }
  const bl = document.getElementById('btnLang');
  if(bl) bl.textContent = '🌐 ' + I18N.lang.toUpperCase();
}
function setLang(l, opts){
  if(!LANGS[l]) return;
  I18N.lang = l;
  if(!opts || opts.persist !== false){
    try{ localStorage.setItem('tuerca_lang', l); }catch(e){}
  }
  aplicarIdioma();
}
/* selector: cicla gl → es → en */
(function(){
  const bl = document.getElementById('btnLang');
  if(bl) bl.addEventListener('click', () => {
    const i = I18N.ordem.indexOf(I18N.lang);
    setLang(I18N.ordem[(i + 1) % I18N.ordem.length]);
  });
  aplicarIdioma();
})();
